pub fn sentence(template: &str, count: usize, first: &str) -> String {
    let mut parts = template.splitn(3, "{}");
    format!(
        "{}{}{}{}{}",
        parts.next().unwrap_or_default(),
        count,
        parts.next().unwrap_or_default(),
        first,
        parts.next().unwrap_or_default()
    )
}
